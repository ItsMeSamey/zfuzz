pub fn classOf(cp: u21) Class {
    var lo: usize = 0;
    var hi: usize = class_ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const range = class_ranges[mid];
        if (cp < range.lo) hi = mid else if (cp > range.hi) lo = mid + 1 else return range.class;
    }
    return .other;
}

pub fn toLower(cp: u21) u21 {
    if (cp >= 'A' and cp <= 'Z') return cp + ('a' - 'A');
    var lo: usize = 0;
    var hi: usize = lower_pairs.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const pair = lower_pairs[mid];
        if (cp < pair.from) hi = mid else if (cp > pair.from) lo = mid + 1 else return pair.to;
    }
    return cp;
}

